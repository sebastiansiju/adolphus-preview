const fs = require('fs');
const babel = require('next/dist/compiled/babel/core');
const React = require('react');
const {renderToStaticMarkup} = require('react-dom/server');
const source = fs.readFileSync('app/page.js','utf8');
const result = babel.transformSync(source,{presets:[[require('next/dist/compiled/babel/preset-react'),{runtime:'automatic'}]],plugins:[require('next/dist/compiled/babel/plugin-transform-modules-commonjs')],babelrc:false,configFile:false});
const compiled = {exports:{}};
new Function('require','module','exports',result.code)(require,compiled,compiled.exports);
const markup = renderToStaticMarkup(React.createElement(compiled.exports.default)).replaceAll('/adolphus-logo.png','public/adolphus-logo.png').replaceAll('/banquet-hero.png','public/banquet-hero.png');
const interactions = fs.readFileSync('public/interactions.js','utf8');
fs.writeFileSync('preview.html','<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Adolphus Group — Recruitment in London</title><style>'+fs.readFileSync('app/site.css','utf8')+'</style></head><body>'+markup+'<script>'+interactions+'</script></body></html>');
console.log('Standalone preview rendered successfully.');
